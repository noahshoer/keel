//! Writes the TypeScript bindings for every type that crosses IPC (and the
//! wasm boundary) into `web/src/bindings/`, plus an `index.ts` that
//! re-exports them. Run with `cargo test -p keel-core --features ts`;
//! `scripts/check-bindings.sh` fails when the committed files are stale.
#![cfg(feature = "ts")]

use std::path::PathBuf;

use keel_core::calendar::{DayCell, MonthView};
use keel_core::commands::{Action, ApplyResult, Command, DueEdit};
use keel_core::editor::{
    AddPlan, EditPlan, EditorValues, EditorView, LocationChoice, LocationKind, Pick, PreviewChip, ReminderDraft, TaskPatch,
    TitleSegment,
};
use keel_core::filter::FilterGroup;
use keel_core::ids::Id;
use keel_core::import::todoist::ImportSummary;
use keel_core::model::{
    Due, Duration, DurationUnit, Filter, Label, Priority, Project, Reminder, ReminderType, Section, Task,
    ViewStyle,
};
use keel_core::quickadd::{QuickAdd, Span, SpanKind};
use keel_core::recurrence::Recurrence;
use keel_core::reminders::{PlannedReminder, ReminderSettings};
use keel_core::search::SearchResults;
use keel_core::views::{Card, CardMode, CardRow, DateGroup, DateGroupMode, DueBucket, Progress};
use ts_rs::TS;

/// `TS_RS_EXPORT_DIR` from `.cargo/config.toml` (absolute: `relative = true`).
fn bindings_dir() -> PathBuf {
    PathBuf::from(env!("TS_RS_EXPORT_DIR"))
}

macro_rules! export_all {
    ($($t:ty),* $(,)?) => {
        $( <$t as TS>::export_all().expect(concat!("export ", stringify!($t))); )*
    };
}

/// One `export type * from "./X";` per generated file, sorted.
fn write_index(dir: &std::path::Path) {
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .expect("read bindings dir")
        .map(|e| e.expect("dir entry").file_name().to_string_lossy().into_owned())
        .filter_map(|n| n.strip_suffix(".ts").map(str::to_string))
        .filter(|n| n != "index")
        .collect();
    names.sort();
    let mut out = String::from("// Generated by crates/core/tests/ts_bindings.rs. Do not edit.\n");
    for n in names {
        out.push_str(&format!("export type * from \"./{n}\";\n"));
    }
    std::fs::write(dir.join("index.ts"), out).expect("write index.ts");
}

#[test]
fn bindings_cover_ipc_types() {
    export_all!(
        // model
        Id, Task, Project, Section, Label, Filter, Reminder, ReminderType, Due, Duration, DurationUnit,
        Priority, ViewStyle, Recurrence,
        // commands
        Action, Command, ApplyResult, DueEdit,
        // views / quick add / calendar (the wasm boundary)
        CardRow, Card, CardMode, DateGroup, DateGroupMode, Progress, DueBucket, QuickAdd, Span, SpanKind, MonthView, DayCell,
        // the editor (the wasm boundary)
        EditorValues, EditorView, ReminderDraft, Pick, TaskPatch, LocationChoice, LocationKind, TitleSegment, PreviewChip,
        AddPlan, EditPlan,
        // query results
        PlannedReminder, ReminderSettings, SearchResults, FilterGroup, ImportSummary,
    );
    let dir = bindings_dir();
    write_index(&dir);

    let task = std::fs::read_to_string(dir.join("Task.ts")).expect("Task.ts written");
    assert!(task.contains("id: Id"), "{task}");
    assert!(task.contains("content: string"), "{task}");
    // i64 crosses JSON as a number, not a bigint.
    assert!(task.contains("child_order: number"), "{task}");

    let index = std::fs::read_to_string(dir.join("index.ts")).expect("index.ts written");
    assert!(index.contains("export type * from \"./Task\";"), "{index}");
    assert!(!index.contains("./index\""), "{index}");
}
